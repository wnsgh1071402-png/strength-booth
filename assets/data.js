export function getArea(areaId) {
  return AREAS.find((a) => a.id === areaId) || null;
}

export function getStrength(areaId, strengthId) {
  const area = getArea(areaId);
  return area ? area.strengths.find((s) => s.id === strengthId) || null : null;
}
