export function getArea(areaId) {
  return AREAS.find((a) => a.id === areaId) || null;
}

export function getStrength(areaId, strengthId) {
  const area = getArea(areaId);
  return area ? area.strengths.find((s) => s.id === strengthId) || null : null;
}

/**
 * 영역과 무관하게 강점을 찾는다.
 * interpret.pairs(함께 나타나는 강점)는 다른 영역의 강점을 가리킬 수 있어서 필요하다.
 * @returns {{strength, area}|null}
 */
export function findStrength(strengthId) {
  for (const area of AREAS) {
    const strength = area.strengths.find((s) => s.id === strengthId);
    if (strength) return { strength, area };
  }
  return null;
}
